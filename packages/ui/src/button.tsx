/**
 * The classes for a button, merged so a variant's border or colour wins over the base's (`border-transparent`):
 * Tailwind orders same-property utilities by name, not by where they appear, so unmerged the base's would win
 * wherever these are used on their own (`<Link className={buttonVariants(...)}>`).
 */
const buttonVariants = (props?: Parameters<typeof variants>[0]) => cn(variants(props))

function Button({
  className,
  variant = "default",
  size = "default",
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof variants>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={buttonVariants({ variant, size, className })}
      {...props}
    />
  )
}

export { Button, buttonVariants }
